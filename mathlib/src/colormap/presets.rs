/// Linear interpolation of scalar `t` in [0, 1] over a colormap slice.
/// Returns RGB in [0, 255].
#[inline]
#[allow(
    clippy::cast_possible_truncation,
    clippy::cast_precision_loss,
    clippy::cast_sign_loss
)]
fn sample_colormap(samples: &[[f32; 3]], t: f64) -> Rgb {
    let t = t.clamp(0.0, 1.0) as f32;
    let n = samples.len();
    if n <= 1 {
        let [r, g, b] = samples.first().copied().unwrap_or([0.0, 0.0, 0.0]);
        return [
            (r * 255.0).round().clamp(0.0, 255.0) as u8,
            (g * 255.0).round().clamp(0.0, 255.0) as u8,
            (b * 255.0).round().clamp(0.0, 255.0) as u8,
        ];
    }
    let idx = t * (n - 1) as f32;
    let i0 = (idx as usize).min(n - 2);
    let i1 = i0 + 1;
    let frac = idx - i0 as f32;
    let [r0, g0, b0] = samples[i0];
    let [r1, g1, b1] = samples[i1];
    let r = r0 + (r1 - r0) * frac;
    let g = g0 + (g1 - g0) * frac;
    let b = b0 + (b1 - b0) * frac;
    [
        (r * 255.0).round().clamp(0.0, 255.0) as u8,
        (g * 255.0).round().clamp(0.0, 255.0) as u8,
        (b * 255.0).round().clamp(0.0, 255.0) as u8,
    ]
}

