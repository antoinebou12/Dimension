/// Viridis colormap: purple/blue (low) → green (mid) → yellow (high).
/// Perceptually uniform; good for scientific visualization.
///
/// # Examples
///
/// ```
/// use mathlib::colormap::scalar_to_rgb_viridis;
///
/// let low = scalar_to_rgb_viridis(0.0);   // dark purple
/// let mid = scalar_to_rgb_viridis(0.5);   // green
/// let high = scalar_to_rgb_viridis(1.0);  // yellow
/// ```
#[inline]
#[must_use]
pub fn scalar_to_rgb_viridis(t: f64) -> Rgb {
    sample_colormap(&VIRIDIS, t)
}

/// Magma colormap: black/purple (low) → red/orange (mid) → yellow/white (high).
#[inline]
#[must_use]
pub fn scalar_to_rgb_magma(t: f64) -> Rgb {
    sample_colormap(&MAGMA, t)
}

/// Inferno colormap: black (low) → red (mid) → yellow (high).
#[inline]
#[must_use]
pub fn scalar_to_rgb_inferno(t: f64) -> Rgb {
    sample_colormap(&INFERNO, t)
}

/// Plasma colormap: purple/blue (low) → pink (mid) → yellow (high).
#[inline]
#[must_use]
pub fn scalar_to_rgb_plasma(t: f64) -> Rgb {
    sample_colormap(&PLASMA, t)
}

/// Select a preset colormap by name and map scalar `t` in [0, 1] to RGB.
///
/// Supported names: `"viridis"`, `"magma"`, `"inferno"`, `"plasma"`.
/// Returns viridis for unknown names.
#[inline]
#[must_use]
pub fn scalar_to_rgb_preset(name: &str, t: f64) -> Rgb {
    match name {
        "magma" => scalar_to_rgb_magma(t),
        "inferno" => scalar_to_rgb_inferno(t),
        "plasma" => scalar_to_rgb_plasma(t),
        _ => scalar_to_rgb_viridis(t),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn viridis_bounds() {
        let low = scalar_to_rgb_viridis(0.0);
        let high = scalar_to_rgb_viridis(1.0);
        assert!(low[0] < 100);
        assert!(high[2] < low[2]);
    }

    #[test]
    fn magma_bounds() {
        let low = scalar_to_rgb_magma(0.0);
        let high = scalar_to_rgb_magma(1.0);
        assert!(low[0] < 50);
        assert!(high[0] > 200);
    }

    #[test]
    fn preset_fallback() {
        let v = scalar_to_rgb_preset("viridis", 0.5);
        let u = scalar_to_rgb_preset("unknown", 0.5);
        assert_eq!(v, u);
    }
}
